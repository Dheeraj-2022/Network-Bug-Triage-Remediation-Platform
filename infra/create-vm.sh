#!/usr/bin/env bash
#
# infra/create-vm.sh
#
# Create a multi-VM testbed using Vagrant (VirtualBox provider).
# - Generates infra/Vagrantfile for N agent nodes on a host-only network
# - Generates infra/inventory.ini matching the groups used by infra/site.yml
#   ([agents] = all nodes, [controller] = node1)
# - Optionally runs `vagrant up` (--up)
#
# Usage:
#   bash infra/create-vm.sh [NUM_NODES] [--up]
#
# Examples:
#   bash infra/create-vm.sh 5
#   bash infra/create-vm.sh 7 --up
#
# Environment overrides:
#   BOX=bento/ubuntu-22.04   Vagrant base box
#   BASE_IP=192.168.56       host-only /24 prefix (nodes get .101, .102, ...)
#   VM_MEMORY=2048 VM_CPUS=1
#
set -euo pipefail

NUM_NODES="${1:-5}"
DO_VAGRANT_UP=false
for arg in "$@"; do
  [[ "${arg}" == "--up" ]] && DO_VAGRANT_UP=true
done
if [[ "${NUM_NODES}" == "--up" ]]; then
  NUM_NODES=5
fi
if ! [[ "${NUM_NODES}" =~ ^[0-9]+$ ]] || (( NUM_NODES < 1 || NUM_NODES > 150 )); then
  echo "ERROR: NUM_NODES must be an integer between 1 and 150 (got '${NUM_NODES}')" >&2
  exit 1
fi

WORKDIR="$(cd "$(dirname "$0")" && pwd)"
VAGRANTFILE="${WORKDIR}/Vagrantfile"
INVENTORY="${WORKDIR}/inventory.ini"

BOX="${BOX:-bento/ubuntu-22.04}"
BASE_IP="${BASE_IP:-192.168.56}"   # VirtualBox host-only range (192.168.56.0/21 is allowed by default)
VM_MEMORY="${VM_MEMORY:-2048}"
VM_CPUS="${VM_CPUS:-1}"
# Keep the shared Vagrant insecure key so one ansible_ssh_private_key_file works for every node.
INSECURE_KEY="~/.vagrant.d/insecure_private_key"

echo "Creating Vagrantfile for ${NUM_NODES} nodes at ${VAGRANTFILE}"

cat > "${VAGRANTFILE}" <<VAGRANT
# Auto-generated by infra/create-vm.sh - do not edit by hand (re-run the script instead)
Vagrant.configure("2") do |config|
  config.vm.box = "${BOX}"
  config.vm.synced_folder ".", "/vagrant", disabled: true
  config.ssh.insert_key = false

  (1..${NUM_NODES}).each do |i|
    config.vm.define "node#{i}" do |node|
      host_ip = "${BASE_IP}." + (100 + i).to_s
      node.vm.hostname = "node#{i}"
      node.vm.network "private_network", ip: host_ip

      node.vm.provider "virtualbox" do |vb|
        vb.name = "nbt-node#{i}"
        vb.memory = ${VM_MEMORY}
        vb.cpus = ${VM_CPUS}
      end

      node.vm.provision "shell", inline: <<-SHELL
        set -e
        export DEBIAN_FRONTEND=noninteractive
        apt-get update -y
        apt-get install -y python3 python3-venv python3-pip git rsync iproute2 net-tools tcpdump rdma-core
      SHELL
    end
  end
end
VAGRANT

if [[ -f "${INVENTORY}" ]]; then
  cp "${INVENTORY}" "${INVENTORY}.bak"
  echo "Existing inventory backed up to ${INVENTORY}.bak"
fi

echo "Writing Ansible inventory to ${INVENTORY}"
{
  echo "# infra/inventory.ini - auto-generated by infra/create-vm.sh for ${NUM_NODES} nodes"
  echo "# Groups match infra/site.yml: [controller] runs the processor, [agents] run the telemetry agent."
  echo ""
  echo "[agents]"
  for ((i = 1; i <= NUM_NODES; i++)); do
    echo "node${i} ansible_host=${BASE_IP}.$((100 + i)) ansible_user=vagrant ansible_ssh_private_key_file=${INSECURE_KEY}"
  done
  echo ""
  echo "[controller]"
  echo "node1 ansible_host=${BASE_IP}.101 ansible_user=vagrant ansible_ssh_private_key_file=${INSECURE_KEY}"
  echo ""
  echo "[all:vars]"
  echo "ansible_python_interpreter=/usr/bin/python3"
} > "${INVENTORY}"

echo ""
echo "Vagrantfile and inventory created."
echo "To bring up the VMs (requires Vagrant + VirtualBox):"
echo "  cd ${WORKDIR} && vagrant up"

if [[ "${DO_VAGRANT_UP}" == true ]]; then
  if ! command -v vagrant >/dev/null 2>&1; then
    echo "ERROR: --up requested but 'vagrant' is not on PATH. Install Vagrant + VirtualBox and re-run, or run 'vagrant up' manually." >&2
    exit 1
  fi
  echo "Running 'vagrant up' now..."
  (cd "${WORKDIR}" && vagrant up)
fi

echo ""
echo "Next steps:"
echo "  ansible all -m ping                       # verify SSH reachability (uses ansible.cfg -> infra/inventory.ini)"
echo "  ansible-playbook infra/site.yml           # deploy controller + agents (see docs/ansible.md)"
